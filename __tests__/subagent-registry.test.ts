/**
 * Tests for lib/orchestration/subagent-registry.ts
 *
 * All fs/promises calls are mocked — no real disk I/O occurs.
 * The in-memory store is reset before each test via globalThis.
 */

import fs from "fs/promises";
import type { SubagentSpec } from "@/lib/orchestration/subagent-types";

// ─── Mock fs/promises ─────────────────────────────────────────────────────────

jest.mock("fs/promises", () => ({
  mkdir: jest.fn().mockResolvedValue(undefined),
  writeFile: jest.fn().mockResolvedValue(undefined),
  readFile: jest.fn().mockRejectedValue(Object.assign(new Error("ENOENT"), { code: "ENOENT" })),
  readdir: jest.fn().mockResolvedValue([]),
  unlink: jest.fn().mockResolvedValue(undefined),
}));

// ─── Import after mocks ───────────────────────────────────────────────────────

import {
  registerSubagent,
  getSubagent,
  listSubagents,
  updateSubagentPerformance,
  retireSubagent,
  validateSubagentSecurity,
  getBuiltinTemplates,
} from "@/lib/orchestration/subagent-registry";

// ─── Helpers ──────────────────────────────────────────────────────────────────

function resetStore(): void {
  const g = globalThis as typeof globalThis & {
    __subagentRegistryStore?: Map<string, SubagentSpec>;
  };
  if (g.__subagentRegistryStore) {
    g.__subagentRegistryStore.clear();
  }
}

function makeSpec(overrides: Partial<SubagentSpec> = {}): SubagentSpec {
  return {
    id: "test/spec-a",
    name: "Test Spec A",
    parentAgent: "claude-code",
    runtimePreference: "claude-direct",
    role: "Test role",
    bestFor: ["testing"],
    notFor: ["production"],
    allowedFiles: ["lib/orchestration/**"],
    blockedFiles: [".env"],
    allowedCommands: ["pnpm typecheck"],
    blockedCommands: ["git push"],
    promptTemplatePath: "templates/test.md",
    obsidianPath: "subagents/test",
    source: "builtin",
    successCount: 0,
    failureCount: 0,
    status: "active",
    securityReport: { level: "clean", message: "pre-validated" },
    ...overrides,
  };
}

// ─── Tests ───────────────────────────────────────────────────────────────────

beforeEach(() => {
  resetStore();
  jest.clearAllMocks();
});

// ---------------------------------------------------------------------------
// validateSubagentSecurity
// ---------------------------------------------------------------------------

describe("validateSubagentSecurity", () => {
  it("returns clean for a safe builtin spec", () => {
    const report = validateSubagentSecurity(makeSpec());
    expect(report.level).toBe("clean");
  });

  it("returns rejected when allowedCommands contains a dangerous command", () => {
    const spec = makeSpec({ allowedCommands: ["git push origin main"] });
    const report = validateSubagentSecurity(spec);
    expect(report.level).toBe("rejected");
    expect(report.details?.some((d) => d.includes("git push origin main"))).toBe(true);
  });

  it("returns rejected when allowedFiles contains .env", () => {
    const spec = makeSpec({ allowedFiles: [".env.local"] });
    const report = validateSubagentSecurity(spec);
    expect(report.level).toBe("rejected");
  });

  it("returns rejected when allowedFiles contains package.json", () => {
    const spec = makeSpec({ allowedFiles: ["package.json"] });
    const report = validateSubagentSecurity(spec);
    expect(report.level).toBe("rejected");
  });

  it("returns warning when external source has no sourceHash", () => {
    const spec = makeSpec({ source: "clawhub", sourceHash: undefined });
    const report = validateSubagentSecurity(spec);
    expect(report.level).toBe("warning");
    expect(report.details?.some((d) => d.includes("sourceHash"))).toBe(true);
  });

  it("returns warning when a command appears in both allowedCommands and blockedCommands", () => {
    const spec = makeSpec({
      allowedCommands: ["pnpm lint"],
      blockedCommands: ["pnpm lint"],
    });
    const report = validateSubagentSecurity(spec);
    expect(report.level).toBe("warning");
  });
});

