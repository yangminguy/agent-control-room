describe("registerSubagent", () => {
  it("registers a valid spec and returns it", async () => {
    const spec = makeSpec();
    const result = await registerSubagent(spec);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.id).toBe(spec.id);
    }
  });

  it("attaches the generated securityReport to the stored spec", async () => {
    const spec = makeSpec({ source: "clawhub" }); // triggers warning
    const result = await registerSubagent(spec);
    expect(result.success).toBe(true);
    if (result.success) {
      // The stored spec's report is regenerated by validateSubagentSecurity
      expect(result.data.securityReport.level).toBe("warning");
    }
  });

  it("blocks a spec with a rejected security report", async () => {
    const spec = makeSpec({ allowedCommands: ["git push origin main"] });
    const result = await registerSubagent(spec);
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.error).toMatch(/rejected/i);
    }
  });

  it("persists to disk after registration", async () => {
    const mockFs = fs as jest.Mocked<typeof fs>;
    await registerSubagent(makeSpec());
    expect(mockFs.writeFile).toHaveBeenCalled();
  });
});

