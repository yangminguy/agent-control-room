describe("listSubagents", () => {
  it("returns all registered subagents", async () => {
    await registerSubagent(makeSpec({ id: "test/a", parentAgent: "claude-code" }));
    await registerSubagent(makeSpec({ id: "test/b", parentAgent: "codex" }));
    const result = await listSubagents();
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.length).toBe(2);
    }
  });

  it("filters by parentAgent", async () => {
    await registerSubagent(makeSpec({ id: "test/a", parentAgent: "claude-code" }));
    await registerSubagent(makeSpec({ id: "test/b", parentAgent: "codex" }));
    const result = await listSubagents("codex");
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.every((s) => s.parentAgent === "codex")).toBe(true);
      expect(result.data.length).toBe(1);
    }
  });

  it("returns empty array when registry is empty", async () => {
    const result = await listSubagents();
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data).toEqual([]);
    }
  });
});

