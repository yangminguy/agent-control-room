describe("getBuiltinTemplates", () => {
  it("returns templates for all three parent agents", () => {
    const templates = getBuiltinTemplates();
    const parents = new Set(templates.map((t) => t.parentAgent));
    expect(parents.has("claude-code")).toBe(true);
    expect(parents.has("codex")).toBe(true);
    expect(parents.has("antigravity")).toBe(true);
  });

  it("includes expected builtin ids", () => {
    const templates = getBuiltinTemplates();
    const ids = templates.map((t) => t.id);
    expect(ids).toContain("claude/architecture-reviewer");
    expect(ids).toContain("codex/regression-qa");
    expect(ids).toContain("antigravity/visual-qa");
  });

  it("all builtin templates have clean security reports", () => {
    const templates = getBuiltinTemplates();
    for (const t of templates) {
      expect(t.securityReport.level).toBe("clean");
    }
  });

  it("all builtin templates have source=builtin", () => {
    const templates = getBuiltinTemplates();
    for (const t of templates) {
      expect(t.source).toBe("builtin");
    }
  });

  it("no builtin template has a dangerous allowedCommand", () => {
    const templates = getBuiltinTemplates();
    for (const t of templates) {
      const report = validateSubagentSecurity(t);
      expect(report.level).not.toBe("rejected");
    }
  });
});
