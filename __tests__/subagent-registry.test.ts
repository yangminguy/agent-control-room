describe("retireSubagent", () => {
  it("sets status to retired", async () => {
    await registerSubagent(makeSpec({ id: "test/retire" }));
    const result = await retireSubagent("test/retire", "no longer needed");
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.status).toBe("retired");
    }
  });

  it("includes the reason in the securityReport message", async () => {
    await registerSubagent(makeSpec({ id: "test/retire2" }));
    const result = await retireSubagent("test/retire2", "deprecated api");
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.securityReport.message).toContain("deprecated api");
    }
  });

  it("returns error for unknown id", async () => {
    const result = await retireSubagent("nonexistent", "reason");
    expect(result.success).toBe(false);
  });
});

