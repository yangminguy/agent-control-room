describe("updateSubagentPerformance", () => {
  it("increments successCount on success=true", async () => {
    await registerSubagent(makeSpec({ id: "test/perf" }));
    const result = await updateSubagentPerformance("test/perf", true);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.successCount).toBe(1);
      expect(result.data.failureCount).toBe(0);
    }
  });

  it("increments failureCount on success=false", async () => {
    await registerSubagent(makeSpec({ id: "test/perf2" }));
    const result = await updateSubagentPerformance("test/perf2", false);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.failureCount).toBe(1);
      expect(result.data.successCount).toBe(0);
    }
  });

  it("sets lastUsedAt after update", async () => {
    await registerSubagent(makeSpec({ id: "test/perf3" }));
    const result = await updateSubagentPerformance("test/perf3", true);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.lastUsedAt).toBeDefined();
    }
  });

  it("computes averageQualityScore when score is provided", async () => {
    await registerSubagent(makeSpec({ id: "test/perf4", successCount: 0, failureCount: 0 }));
    await updateSubagentPerformance("test/perf4", true, 80);
    const result = await updateSubagentPerformance("test/perf4", true, 100);
    expect(result.success).toBe(true);
    if (result.success) {
      // Running average of two runs
      expect(result.data.averageQualityScore).toBeGreaterThan(0);
    }
  });

  it("returns error for unknown subagent id", async () => {
    const result = await updateSubagentPerformance("nonexistent", true);
    expect(result.success).toBe(false);
  });
});

